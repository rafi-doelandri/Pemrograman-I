    private void TambahButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_TambahButtonActionPerformed
        // TODO add your handling code here:
        try {
            // Ambil ID dari objek yang dipilih di ComboBox
            Film selectedFilm = (Film) FilmComboBox.getSelectedItem();
            Studio selectedStudio = (Studio) StudioComboBox.getSelectedItem();
            
            if (selectedFilm == null || selectedStudio == null || TanggalTayangDateChooser.getDate() == null || HargaTiketTextField.getText().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Semua formulir harus diisi!", "Peringatan", JOptionPane.WARNING_MESSAGE);
                return;
            }

            int idFilm = selectedFilm.getIdFilm();
            int idStudio = selectedStudio.getIdStudio();
            
            // Konversi java.util.Date ke java.sql.Date dan java.sql.Time
            java.sql.Date sqlDate = new java.sql.Date(TanggalTayangDateChooser.getDate().getTime());
            java.sql.Time sqlTime = new java.sql.Time(((Date) JamTayangSpinner.getValue()).getTime());
            
            double harga = Double.parseDouble(HargaTiketTextField.getText());

            Showtime jadwal = new Showtime(0, idFilm, idStudio, sqlDate, sqlTime, harga);
            ShowtimeDAO dao = new ShowtimeDAO();

            if (dao.insertShowtime(jadwal)) {
                JOptionPane.showMessageDialog(this, "Jadwal tayang berhasil ditambahkan!");
                loadDataTable();
                clearFields();
            } else {
                JOptionPane.showMessageDialog(this, "Gagal menambahkan jadwal.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Harga tiket harus berupa angka!", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_TambahButtonActionPerformed

