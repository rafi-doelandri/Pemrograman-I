    private void JadwalTayangTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_JadwalTayangTableMouseClicked
        // TODO add your handling code here:
        int row = JadwalTayangTable.getSelectedRow();
        if (row != -1) {
            idJadwalTerpilih = Integer.parseInt(JadwalTayangTable.getValueAt(row, 0).toString());
            
            // 1. Set ComboBox Film
            String judulFilm = JadwalTayangTable.getValueAt(row, 1).toString();
            for (int i = 0; i < FilmComboBox.getItemCount(); i++) {
                if (FilmComboBox.getItemAt(i).toString().equals(judulFilm)) {
                    FilmComboBox.setSelectedIndex(i);
                    break;
                }
            }

            // 2. Set ComboBox Studio
            String namaStudio = JadwalTayangTable.getValueAt(row, 2).toString();
            for (int i = 0; i < StudioComboBox.getItemCount(); i++) {
                if (StudioComboBox.getItemAt(i).toString().equals(namaStudio)) {
                    StudioComboBox.setSelectedIndex(i);
                    break;
                }
            }

            // 3. Set Tanggal
            try {
                Date tanggal = java.sql.Date.valueOf(JadwalTayangTable.getValueAt(row, 3).toString());
                TanggalTayangDateChooser.setDate(tanggal);
            } catch (Exception e) { e.printStackTrace(); }

            // 4. Set Jam
            try {
                SimpleDateFormat format = new SimpleDateFormat("HH:mm:ss");
                Date jam = format.parse(JadwalTayangTable.getValueAt(row, 4).toString());
                JamTayangSpinner.setValue(jam);
            } catch (Exception e) { e.printStackTrace(); }

            // 5. Set Harga
            HargaTiketTextField.setText(JadwalTayangTable.getValueAt(row, 5).toString());
        }
    }//GEN-LAST:event_JadwalTayangTableMouseClicked

