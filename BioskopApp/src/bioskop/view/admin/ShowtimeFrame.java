    private void loadComboBoxData() {
        FilmComboBox.removeAllItems();
        StudioComboBox.removeAllItems();

        // Load Film
        FilmDAO filmDAO = new FilmDAO();
        for (Film f : filmDAO.getAllFilms()) {
            FilmComboBox.addItem(f); // Memasukkan objek Film utuh
        }

        // Load Studio
        StudioDAO studioDAO = new StudioDAO();
        for (Studio s : studioDAO.getAllStudios()) {
            StudioComboBox.addItem(s); // Memasukkan objek Studio utuh
        }
    }

    private void loadDataTable() {
        DefaultTableModel model = (DefaultTableModel) JadwalTayangTable.getModel();
        model.setRowCount(0);

        ShowtimeDAO dao = new ShowtimeDAO();
        List<Showtime> list = dao.getAllShowtimes();

        // Urutan kolom: ID Jadwal, Judul Film, Nama Studio, Tanggal, Jam, Harga
        for (Showtime s : list) {
            model.addRow(new Object[]{
                s.getIdJadwal(),
                s.getJudulFilm(),
                s.getNamaStudio(),
                s.getTanggalTayang(),
                s.getJamTayang(),
                s.getHargaTiket()
            });
        }
    }

    private void clearFields() {
        if (FilmComboBox.getItemCount() > 0) FilmComboBox.setSelectedIndex(0);
        if (StudioComboBox.getItemCount() > 0) StudioComboBox.setSelectedIndex(0);
        TanggalTayangDateChooser.setDate(null);
        JamTayangSpinner.setValue(new Date()); // Reset ke jam saat ini
        HargaTiketTextField.setText("");
        idJadwalTerpilih = -1;
    }
