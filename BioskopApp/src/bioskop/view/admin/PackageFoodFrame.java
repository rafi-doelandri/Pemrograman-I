    private void SimpanPaketButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SimpanPaketButtonActionPerformed
        // TODO add your handling code here:
        String namaPaket = NamaPaketTextField.getText();
        String deskripsi = DeskripsiTextArea.getText();
        String hargaStr = HargaTextField.getText();

        // Validasi
        if (namaPaket.isEmpty() || hargaStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama Paket dan Harga Utama harus diisi!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        if (keranjang.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Keranjang paket tidak boleh kosong! Tambahkan minimal 1 makanan/minuman.", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double hargaPaket = Double.parseDouble(hargaStr);
            
            // 1. Buat Objek Header Paket
            FoodPackage paketBaru = new FoodPackage(0, namaPaket, deskripsi, hargaPaket);
            
            // 2. Tempelkan isi keranjang kita ke dalam paket tersebut
            paketBaru.setDetails(keranjang);

            // 3. Kirimkan ke DAO untuk diproses SQL-nya
            FoodPackageDAO dao = new FoodPackageDAO();
            if (dao.insertFoodPackage(paketBaru)) {
                JOptionPane.showMessageDialog(this, "Paket Makanan berhasil disimpan ke Database secara permanen!");
                clearSemuaForm(); // Kosongkan semuanya agar siap input paket baru
            } else {
                JOptionPane.showMessageDialog(this, "Gagal menyimpan paket ke Database.", "Error", JOptionPane.ERROR_MESSAGE);
            }
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Kolom harga harus berupa angka!", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_SimpanPaketButtonActionPerformed

    private void KeranjangTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_KeranjangTableMouseClicked
        // TODO add your handling code here:
        indexKeranjangTerpilih = KeranjangTable.getSelectedRow();
        if (indexKeranjangTerpilih != -1) {
            FoodPackageDetail detail = keranjang.get(indexKeranjangTerpilih);
            
            // Set MakananComboBox
            for (int i = 0; i < MakananComboBox.getItemCount(); i++) {
                if (MakananComboBox.getItemAt(i).toString().equals(detail.getNamaFood())) {
                    MakananComboBox.setSelectedIndex(i);
                    break;
                }
            }
            
            // Set Spinner Jumlah
            JumlahSpinner.setValue(detail.getJumlah());
        }
    }//GEN-LAST:event_KeranjangTableMouseClicked

    private void TambahPaketButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_TambahPaketButtonActionPerformed
        // TODO add your handling code here:
        Food selectedFood = (Food) MakananComboBox.getSelectedItem();
        int jumlah = Integer.parseInt(JumlahSpinner.getValue().toString());

        if (selectedFood == null || jumlah <= 0) {
            JOptionPane.showMessageDialog(this, "Pilih makanan dan pastikan jumlah lebih dari 0!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Membuat objek detail sementara (ID Paket dan ID Detail diset 0 dulu karena belum masuk database)
        FoodPackageDetail detailBaru = new FoodPackageDetail(0, 0, selectedFood.getIdFood(), jumlah);
        detailBaru.setNamaFood(selectedFood.getNamaFood()); // Set nama untuk ditampilkan di tabel
        
        keranjang.add(detailBaru); // Masukkan ke memori RAM
        refreshKeranjangTabel();   // Gambar ulang tabelnya
    }//GEN-LAST:event_TambahPaketButtonActionPerformed

    private void EditPaketButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EditPaketButtonActionPerformed
        // TODO add your handling code here:
        if (indexKeranjangTerpilih == -1) {
            JOptionPane.showMessageDialog(this, "Pilih data di keranjang yang ingin diedit!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Food selectedFood = (Food) MakananComboBox.getSelectedItem();
        int jumlah = Integer.parseInt(JumlahSpinner.getValue().toString());

        if (selectedFood == null || jumlah <= 0) {
            JOptionPane.showMessageDialog(this, "Pilih makanan dan pastikan jumlah lebih dari 0!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Ambil objek lama, lalu timpa nilainya
        FoodPackageDetail detailLama = keranjang.get(indexKeranjangTerpilih);
        detailLama.setIdFood(selectedFood.getIdFood());
        detailLama.setNamaFood(selectedFood.getNamaFood());
        detailLama.setJumlah(jumlah);

        refreshKeranjangTabel();
    }//GEN-LAST:event_EditPaketButtonActionPerformed

    private void HapusPaketButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_HapusPaketButtonActionPerformed
        // TODO add your handling code here:
        if (indexKeranjangTerpilih == -1) {
            JOptionPane.showMessageDialog(this, "Pilih data di keranjang yang ingin dihapus!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        keranjang.remove(indexKeranjangTerpilih); // Hapus dari memori RAM
        refreshKeranjangTabel();
    }//GEN-LAST:event_HapusPaketButtonActionPerformed

