    private void loadComboBoxData() {
        MakananComboBox.removeAllItems();
        FoodDAO foodDAO = new FoodDAO();
        for (Food f : foodDAO.getAllFoods()) {
            MakananComboBox.addItem(f); // Memasukkan objek Food utuh
        }
    }

    private void refreshKeranjangTabel() {
        DefaultTableModel model = (DefaultTableModel) KeranjangTable.getModel();
        model.setRowCount(0); // Bersihkan tampilan tabel

        // Menampilkan ulang isi list keranjang ke tabel
        // Urutan Kolom: Nama Makanan (0), Jumlah (1)
        for (FoodPackageDetail detail : keranjang) {
            model.addRow(new Object[]{
                detail.getNamaFood(),
                detail.getJumlah()
            });
        }
        indexKeranjangTerpilih = -1; // Reset baris terpilih
    }

    private void clearSemuaForm() {
        NamaPaketTextField.setText("");
        HargaTextField.setText("");
        DeskripsiTextArea.setText("");
        if(MakananComboBox.getItemCount() > 0) MakananComboBox.setSelectedIndex(0);
        JumlahSpinner.setValue(0);
        keranjang.clear(); // Kosongkan keranjang di memori
        refreshKeranjangTabel();
    }

