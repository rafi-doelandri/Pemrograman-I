    private void loadDataTable() {
        DefaultTableModel model = (DefaultTableModel) FoodTable.getModel();
        model.setRowCount(0); // Kosongkan tabel sebelum diisi ulang

        FoodDAO dao = new FoodDAO();
        List<Food> listFood = dao.getAllFoods();

        // Urutan kolom tabel: ID Food, Nama Food, Kategori, Harga, Stok
        for (Food f : listFood) {
            model.addRow(new Object[]{
                f.getIdFood(),
                f.getNamaFood(),
                f.getKategori(),
                f.getHarga(),
                f.getStok()
            });
        }
    }

    private void clearFields() {
        NamaFoodTextField.setText("");
        if (KategoriComboBox.getItemCount() > 0) KategoriComboBox.setSelectedIndex(0);
        HargaTextField.setText("");
        StokSpinner.setValue(0); // Kembalikan stok ke angka 0
        idFoodTerpilih = -1; // Reset ID terpilih
    }

