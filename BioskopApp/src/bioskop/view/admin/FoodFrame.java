    private void FoodTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_FoodTableMouseClicked
        // TODO add your handling code here:
        int row = FoodTable.getSelectedRow();
        if (row != -1) {
            idFoodTerpilih = Integer.parseInt(FoodTable.getValueAt(row, 0).toString());
            NamaFoodTextField.setText(FoodTable.getValueAt(row, 1).toString());
            KategoriComboBox.setSelectedItem(FoodTable.getValueAt(row, 2).toString());
            HargaTextField.setText(FoodTable.getValueAt(row, 3).toString());
            
            // Set nilai JSpinner dari tabel
            int stok = Integer.parseInt(FoodTable.getValueAt(row, 4).toString());
            StokSpinner.setValue(stok);
        }
    }//GEN-LAST:event_FoodTableMouseClicked

    private void TambahButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_TambahButtonActionPerformed
        // TODO add your handling code here:
        String nama = NamaFoodTextField.getText();
        String kategori = KategoriComboBox.getSelectedItem().toString();
        String hargaStr = HargaTextField.getText();
        int stok = Integer.parseInt(StokSpinner.getValue().toString());

        // Validasi input kosong
        if (nama.isEmpty() || hargaStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama dan Harga harus diisi!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double harga = Double.parseDouble(hargaStr); // Konversi harga ke angka desimal
            
            Food food = new Food(0, nama, kategori, harga, stok);
            FoodDAO dao = new FoodDAO();

            if (dao.insertFood(food)) {
                JOptionPane.showMessageDialog(this, "Item makanan/minuman berhasil ditambahkan!");
                loadDataTable();
                clearFields();
            } else {
                JOptionPane.showMessageDialog(this, "Gagal menambahkan item.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Kolom harga harus berupa angka!", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_TambahButtonActionPerformed

    private void EditButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EditButtonActionPerformed
        // TODO add your handling code here:
        if (idFoodTerpilih == -1) {
            JOptionPane.showMessageDialog(this, "Pilih data dari tabel terlebih dahulu!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String nama = NamaFoodTextField.getText();
        String kategori = KategoriComboBox.getSelectedItem().toString();
        String hargaStr = HargaTextField.getText();
        int stok = Integer.parseInt(StokSpinner.getValue().toString());

        if (nama.isEmpty() || hargaStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama dan Harga harus diisi!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double harga = Double.parseDouble(hargaStr);
            
            Food food = new Food(idFoodTerpilih, nama, kategori, harga, stok);
            FoodDAO dao = new FoodDAO();

            if (dao.updateFood(food)) {
                JOptionPane.showMessageDialog(this, "Data berhasil diperbarui!");
                loadDataTable();
                clearFields();
            } else {
                JOptionPane.showMessageDialog(this, "Gagal memperbarui data.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Kolom harga harus berupa angka!", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_EditButtonActionPerformed

    private void HapusButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_HapusButtonActionPerformed
        // TODO add your handling code here:
        if (idFoodTerpilih == -1) {
            JOptionPane.showMessageDialog(this, "Pilih data dari tabel terlebih dahulu!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int konfirmasi = JOptionPane.showConfirmDialog(this, "Yakin ingin menghapus item ini? \nData paket makanan yang menggunakan item ini mungkin juga akan terpengaruh.", "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION);
        
        if (konfirmasi == JOptionPane.YES_OPTION) {
            FoodDAO dao = new FoodDAO();
            if (dao.deleteFood(idFoodTerpilih)) {
                JOptionPane.showMessageDialog(this, "Item berhasil dihapus!");
                loadDataTable();
                clearFields();
            } else {
                JOptionPane.showMessageDialog(this, "Gagal menghapus item.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_HapusButtonActionPerformed

