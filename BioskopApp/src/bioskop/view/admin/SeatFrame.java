    private void KursiTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_KursiTableMouseClicked
        // TODO add your handling code here:
        int row = KursiTable.getSelectedRow();
        if (row != -1) {
            idKursiTerpilih = Integer.parseInt(KursiTable.getValueAt(row, 0).toString());
            
            // 1. Set ComboBox Studio
            String namaStudio = KursiTable.getValueAt(row, 1).toString();
            for (int i = 0; i < StudioComboBox.getItemCount(); i++) {
                if (StudioComboBox.getItemAt(i).toString().equals(namaStudio)) {
                    StudioComboBox.setSelectedIndex(i);
                    break;
                }
            }

            // 2. Set TextField Nomor Kursi
            NmrKursiTextField.setText(KursiTable.getValueAt(row, 2).toString());

            // 3. Set RadioButton Jenis Kursi
            String jenis = KursiTable.getValueAt(row, 3).toString();
            if (jenis.equalsIgnoreCase("Couple")) {
                CoupleRadioButton.setSelected(true);
            } else {
                RegularRadioButton.setSelected(true);
            }

            // 4. Set ComboBox Status
            StatusComboBox.setSelectedItem(KursiTable.getValueAt(row, 4).toString());
        }
    }//GEN-LAST:event_KursiTableMouseClicked

    private void TambahButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_TambahButtonActionPerformed
        // TODO add your handling code here:
        Studio selectedStudio = (Studio) StudioComboBox.getSelectedItem();
        String nomorKursi = NmrKursiTextField.getText();
        String status = StatusComboBox.getSelectedItem().toString();
        
        // Cek radio button mana yang dipilih
        String jenisKursi = RegularRadioButton.isSelected() ? "Regular" : "Couple";

        if (selectedStudio == null || nomorKursi.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Studio dan Nomor Kursi harus diisi!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Seat kursi = new Seat(0, selectedStudio.getIdStudio(), nomorKursi, jenisKursi, status);
        SeatDAO dao = new SeatDAO();

        if (dao.insertSeat(kursi)) {
            JOptionPane.showMessageDialog(this, "Kursi baru berhasil ditambahkan!");
            loadDataTable();
            clearFields();
        } else {
            JOptionPane.showMessageDialog(this, "Gagal menambahkan kursi.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_TambahButtonActionPerformed

    private void EditButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EditButtonActionPerformed
        // TODO add your handling code here:
        if (idKursiTerpilih == -1) {
            JOptionPane.showMessageDialog(this, "Pilih kursi dari tabel terlebih dahulu!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Studio selectedStudio = (Studio) StudioComboBox.getSelectedItem();
        String nomorKursi = NmrKursiTextField.getText();
        String status = StatusComboBox.getSelectedItem().toString();
        String jenisKursi = RegularRadioButton.isSelected() ? "Regular" : "Couple";

        if (selectedStudio == null || nomorKursi.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Studio dan Nomor Kursi harus diisi!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Seat kursi = new Seat(idKursiTerpilih, selectedStudio.getIdStudio(), nomorKursi, jenisKursi, status);
        SeatDAO dao = new SeatDAO();

        if (dao.updateSeat(kursi)) {
            JOptionPane.showMessageDialog(this, "Data kursi berhasil diperbarui!");
            loadDataTable();
            clearFields();
        } else {
            JOptionPane.showMessageDialog(this, "Gagal memperbarui data kursi.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_EditButtonActionPerformed

    private void HapusButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_HapusButtonActionPerformed
        // TODO add your handling code here:
        if (idKursiTerpilih == -1) {
            JOptionPane.showMessageDialog(this, "Pilih kursi dari tabel terlebih dahulu!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int konfirmasi = JOptionPane.showConfirmDialog(this, "Yakin ingin menghapus kursi ini?", "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION);
        
        if (konfirmasi == JOptionPane.YES_OPTION) {
            SeatDAO dao = new SeatDAO();
            if (dao.deleteSeat(idKursiTerpilih)) {
                JOptionPane.showMessageDialog(this, "Kursi berhasil dihapus!");
                loadDataTable();
                clearFields();
            } else {
                JOptionPane.showMessageDialog(this, "Gagal menghapus kursi.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_HapusButtonActionPerformed

