    private void loadComboBoxData(){
        StudioComboBox.removeAllItems();
        StudioDAO studioDAO = new StudioDAO();
        for (Studio s: studioDAO.getAllStudios()){
            StudioComboBox.addItem(s);
        }
    }
    
    private void loadDataTable(){
        DefaultTableModel model = (DefaultTableModel) KursiTable.getModel();
        model.setRowCount(0);

        SeatDAO dao = new SeatDAO();
        List<Seat> list = dao.getAllSeats();

        // Urutan kolom: ID Kursi, Nama Studio, Nomor Kursi, Jenis Kursi, Status
        for (Seat s : list) {
            model.addRow(new Object[]{
                s.getIdKursi(),
                s.getNamaStudio(),
                s.getNomorKursi(),
                s.getJenisKursi(),
                s.getStatus()
            });
        }
    }
    
    private void clearFields(){
        if (StudioComboBox.getItemCount() > 0) StudioComboBox.setSelectedIndex(0);
        NmrKursiTextField.setText("");
        RegularRadioButton.setSelected(true); // Kembali ke default
        StatusComboBox.setSelectedIndex(0);
        idKursiTerpilih = -1;
    }
    
