    private void RiwayatTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_RiwayatTableMouseClicked
        // TODO add your handling code here:
        int barisTerpilih = RiwayatTable.getSelectedRow();
        
        if (barisTerpilih != -1) {
            // Ambil ID Order dari kolom pertama (index 0) yang diklik
            int idOrder = Integer.parseInt(RiwayatTable.getValueAt(barisTerpilih, 0).toString());
            
            DefaultTableModel modelDetail = (DefaultTableModel) DetailTable.getModel();
            modelDetail.setRowCount(0); // Kosongkan tabel detail

            OrderDAO dao = new OrderDAO();

            // 1. Tampilkan Rincian Tiket
            List<OrderTicketDetail> listTiket = dao.getDetailTicketByOrder(idOrder);
            for (OrderTicketDetail t : listTiket) {
                modelDetail.addRow(new Object[]{
                    "Tiket Bioskop",
                    "Kursi " + t.getNomorKursi(),
                    1, // Tiket selalu dihitung 1 per baris/kursi
                    t.getHarga()
                });
            }

            // 2. Tampilkan Rincian Makanan Satuan
            List<OrderFoodDetail> listFood = dao.getDetailFoodByOrder(idOrder);
            for (OrderFoodDetail f : listFood) {
                modelDetail.addRow(new Object[]{
                    "Makanan/Minuman",
                    f.getNamaFood(),
                    f.getJumlah(),
                    f.getSubtotal()
                });
            }

            // 3. Tampilkan Rincian Paket Makanan
            List<OrderPackageDetail> listPackage = dao.getDetailPackageByOrder(idOrder);
            for (OrderPackageDetail p : listPackage) {
                modelDetail.addRow(new Object[]{
                    "Paket Makanan",
                    p.getNamaPaket(),
                    p.getJumlah(),
                    p.getSubtotal()
                });
            }
        }
    }//GEN-LAST:event_RiwayatTableMouseClicked

