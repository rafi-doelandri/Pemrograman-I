    private void loadRiwayatTabel() {
        DefaultTableModel model = (DefaultTableModel) RiwayatTable.getModel();
        model.setRowCount(0); // Kosongkan tabel sebelum diisi

        OrderDAO dao = new OrderDAO();
        List<Order> listOrder = dao.getRiwayatOrderByUser(idUserSesi);

        // Urutan Kolom: ID Pesanan, Tanggal Transaksi, Total Bayar, Status
        for (Order o : listOrder) {
            model.addRow(new Object[]{
                o.getIdOrder(),
                o.getTanggalOrder(),
                o.getTotalHarga(),
                o.getStatusPembayaran()
            });
        }
    }

